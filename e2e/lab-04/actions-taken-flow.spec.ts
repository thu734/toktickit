import { test, expect, api, headers, login, nav, openTicket, capture } from './fixtures/integration';
import { randomUUID } from 'node:crypto';
test('E2E-ACT-01 — real Staff Action lifecycle, assignment, retry, attribution and Requester read-only privacy', async ({ page, lab, browser }, info) => {
    const ticket = lab.tickets[1];
    await login(page, 'staff');
    await openTicket(page, ticket.ticketNumber, true);
    // Ticket Owner differs from both creating Staff and Action assignee.
    let response = await page.request.patch(`${api}/staff/tickets/${ticket.id}/assign`, { headers, data: { assignedStaffId: lab.users.second.id, workflowRevision: 0 } });
    expect(response.status()).toBe(200);
    await openTicket(page, ticket.ticketNumber, true);
    await page.getByRole('button', { name: 'Add Action', exact: true }).click();
    const form = page.getByRole('form', { name: 'Create Action', exact: true });
    await form.getByRole('button', { name: 'Create Action', exact: true }).click();
    await expect(form.getByLabel('Description', { exact: true })).toHaveAttribute('aria-invalid', 'true');
    await form.getByLabel('Description', { exact: true }).fill('Investigate account access and record the reproducible outcome.');
    await form.getByLabel('Follow-Up Required', { exact: true }).check();
    await form.getByRole('button', { name: 'Create Action', exact: true }).click();
    await expect(form.getByLabel('Follow-Up Note', { exact: true })).toHaveAttribute('aria-invalid', 'true');
    expect(await lab.db.actionTaken.count()).toBe(0);
    await capture(page, info, 'actions-taken', 'validation', 'IT_STAFF', ['AC-04', 'AC-05', 'AC-24'], 'Required Follow-Up Note is associated with the field; no Action persisted', 'Follow-Up Note must be at most 1000 characters and is required when follow-up is selected.');
    // Fill the asserted field error before submitting the real API write.
    await form.getByLabel('Follow-Up Note', { exact: true }).fill('Confirm access after the next sign-in.');
    const assignees = form.getByLabel('Assigned to', { exact: true });
    await expect(assignees.locator(`option[value="${lab.users.admin.id}"]`)).toHaveCount(1);
    await expect(assignees.locator(`option[value="${lab.users.inactive.id}"]`)).toHaveCount(0);
    await expect(assignees.locator(`option[value="${lab.users.requester.id}"]`)).toHaveCount(0);
    await assignees.selectOption(String(lab.users.admin.id));
    const created = page.waitForResponse(r => r.url().endsWith(`/tickets/${ticket.id}/actions-taken`) && r.request().method() === 'POST');
    await form.getByRole('button', { name: 'Create Action', exact: true }).click();
    const creation = await created;
    expect(creation.status()).toBe(201);
    const original = await creation.json();
    const actionId = original.action.id;
    await expect(page.getByRole('status').filter({ hasText: 'Action saved.' })).toBeVisible();
    const row = await lab.db.actionTaken.findUniqueOrThrow({ where: { id: actionId } });
    expect(row.performedById).toBe(lab.users.staff.id);
    expect(row.assignedToId).toBe(lab.users.admin.id);
    expect((await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } })).assignedStaffId).toBe(lab.users.second.id);
    // Replay the exact real browser request, not a synthetic mock; no duplicate or revision/event increment.
    const replay = await page.request.post(creation.url(), { headers, data: creation.request().postDataJSON() });
    expect(replay.status()).toBe(201);
    expect(await replay.json()).toEqual(original);
    const changed = await page.request.post(creation.url(), { headers, data: { ...creation.request().postDataJSON(), description: 'Different payload' } });
    expect(changed.status()).toBe(409);
    expect(await lab.db.actionTaken.count()).toBe(1);
    expect(await lab.db.actionAuditEvent.count()).toBe(1);
    expect((await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } })).workflowRevision).toBe(2);
    await capture(page, info, 'actions-taken', 'baseline', 'IT_STAFF', ['AC-01', 'AC-02', 'AC-05', 'AC-11', 'AC-23', 'AC-24'], 'Created shared planned Action; performer, assignee and Ticket Owner differ; replay checked in DB');
    await page.getByRole('button', { name: 'Add Action', exact: true }).click();
    await form.getByLabel('Description', { exact: true }).fill('Alternative workaround no longer needed.');
    await form.getByRole('button', { name: 'Create Action', exact: true }).click();
    await expect(form).toHaveCount(0);
    const second = (await lab.db.actionTaken.findMany({ orderBy: { id: 'asc' } }))[1];
    const displayedOrder = () => page.locator('.actions-taken article').evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')));
    const expectedOrder = [`Action ${actionId}`, `Action ${second.id}`];
    expect(await displayedOrder()).toEqual(expectedOrder);
    let article = page.getByRole('article', { name: `Action ${actionId}`, exact: true });
    await article.getByRole('button', { name: 'Edit Action', exact: true }).click();
    let edit = page.getByRole('form', { name: 'Edit Action', exact: true });
    const priorEvents = await lab.db.actionAuditEvent.findMany({ where: { actionId }, orderBy: { id: 'asc' } });
    await edit.getByLabel('Description', { exact: true }).fill('Investigate account access and save the verified plan.');
    const edited = page.waitForResponse(r => r.url().endsWith(`/actions-taken/${actionId}`) && r.request().method() === 'PATCH');
    await edit.getByRole('button', { name: 'Save changes', exact: true }).click();
    expect((await edited).status()).toBe(200);
    await expect(edit).toHaveCount(0);
    const planned = await lab.db.actionTaken.findUniqueOrThrow({ where: { id: actionId } });
    expect(planned).toMatchObject({ status: 'PLANNED', description: 'Investigate account access and save the verified plan.', assignedToId: row.assignedToId, performedById: row.performedById, createdAt: row.createdAt });
    expect(await displayedOrder()).toEqual(expectedOrder);
    const afterEditEvents = await lab.db.actionAuditEvent.findMany({ where: { actionId }, orderBy: { id: 'asc' } });
    expect(afterEditEvents.slice(0, priorEvents.length)).toEqual(priorEvents);
    expect(afterEditEvents.at(-1)).toMatchObject({ actorId: lab.users.staff.id, eventType: 'UPDATED' });
    await article.getByRole('button', { name: 'Edit Action', exact: true }).click();
    await edit.getByRole('button', { name: 'Complete Action', exact: true }).click();
    await expect(edit.getByLabel('Result', { exact: true })).toHaveAttribute('aria-invalid', 'true');
    await edit.getByLabel('Result', { exact: true }).fill('Access restored; follow-up still required.');
    await edit.getByRole('button', { name: 'Complete Action', exact: true }).click();
    await expect(article.getByRole('heading')).toContainText('COMPLETED');
    await article.getByRole('button', { name: 'Correct completed Action', exact: true }).click();
    edit = page.getByRole('form', { name: 'Edit Action', exact: true });
    await expect(edit.getByLabel('Description', { exact: true })).toHaveAttribute('readonly', '');
    await edit.getByLabel('Result', { exact: true }).fill('Access restored and confirmed by Requester.');
    await edit.getByLabel('Follow-Up Required', { exact: true }).uncheck();
    await edit.getByRole('button', { name: 'Save changes', exact: true }).click();
    await expect(page.getByRole('form', { name: 'Edit Action', exact: true })).toHaveCount(0);
    article = page.getByRole('article', { name: `Action ${second.id}`, exact: true });
    await article.getByRole('button', { name: 'Edit Action', exact: true }).click();
    edit = page.getByRole('form', { name: 'Edit Action', exact: true });
    await edit.getByRole('button', { name: 'Cancel Action', exact: true }).click();
    await expect(edit.getByLabel('Result', { exact: true })).toHaveAttribute('aria-invalid', 'true');
    expect((await lab.db.actionTaken.findUniqueOrThrow({ where: { id: second.id } })).status).toBe('PLANNED');
    await edit.getByLabel('Result', { exact: true }).fill('Cancelled because the primary fix succeeded.');
    await edit.getByRole('button', { name: 'Cancel Action', exact: true }).click();
    await expect(article.getByRole('heading')).toContainText('CANCELLED');
    const final = await lab.db.actionTaken.findUniqueOrThrow({ where: { id: actionId } });
    expect(final.status).toBe('COMPLETED');
    expect(final.result).toBe('Access restored and confirmed by Requester.');
    const cancelled = await lab.db.actionTaken.findUniqueOrThrow({ where: { id: second.id } });
    expect(cancelled).toMatchObject({ status: 'CANCELLED', result: 'Cancelled because the primary fix succeeded.', performedById: second.performedById, createdAt: second.createdAt });
    expect(await displayedOrder()).toEqual(expectedOrder);
    expect(final.performedById).toBe(row.performedById);
    expect(final.createdAt).toEqual(row.createdAt);
    expect(final.followUpRequired).toBe(false);
    const events = await lab.db.actionAuditEvent.findMany({ where: { actionId }, orderBy: { id: 'asc' } });
    expect(events.map((e: any) => e.eventType)).toEqual(['CREATED', 'UPDATED', 'COMPLETED', 'CORRECTED']);
    expect(events.every((e: any) => e.actorId === lab.users.staff.id)).toBe(true);
    const ordered = await page.request.get(`${api}/tickets/${ticket.id}/actions-taken`);
    expect((await ordered.json()).actions.map((a: any) => a.id)).toEqual([actionId, second.id]);
    // Direct API negative cases with a valid Staff session and independent rollback checks.
    const revision = (await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } })).workflowRevision;
    const beforeInvalid = { actions: await lab.db.actionTaken.findMany({ orderBy: { id: 'asc' } }), events: await lab.db.actionAuditEvent.findMany({ orderBy: { id: 'asc' } }) };
    for (const assignedToId of [lab.users.inactive.id, lab.users.requester.id]) {
        response = await page.request.post(`${api}/tickets/${ticket.id}/actions-taken`, { headers, data: { workflowRevision: revision, requestKey: randomUUID(), description: 'Invalid assignment', assignedToId } });
        expect(response.status()).toBe(400);
    }
    response = await page.request.patch(`${api}/tickets/${ticket.id}/actions-taken/${actionId}`, { headers, data: { workflowRevision: revision, performedById: lab.users.admin.id } });
    expect(response.status()).toBe(400);
    response = await page.request.patch(`${api}/tickets/${ticket.id}/actions-taken/${second.id}`, { headers, data: { workflowRevision: revision, status: 'COMPLETED', result: 'Illegal terminal transition' } });
    expect(response.status()).toBe(400);
    expect(await lab.db.actionTaken.count()).toBe(2);
    expect({ actions: await lab.db.actionTaken.findMany({ orderBy: { id: 'asc' } }), events: await lab.db.actionAuditEvent.findMany({ orderBy: { id: 'asc' } }) }).toEqual(beforeInvalid);
    expect((await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } })).workflowRevision).toBe(revision);
    await page.getByRole('button', { name: /Internal Notes/ }).click();
    await page.getByLabel('Private Internal Note', { exact: true }).fill('PRIVATE diagnostic must never reach the Requester.');
    await page.getByRole('button', { name: 'Add Note', exact: true }).click();
    await expect(page.getByText('PRIVATE diagnostic must never reach the Requester.', { exact: true })).toBeVisible();
    const context = await browser.newContext({ baseURL: 'http://127.0.0.1:5207', viewport: page.viewportSize()! });
    try {
        const requester = await context.newPage();
        await login(requester, 'requester');
        await openTicket(requester, ticket.ticketNumber);
        await expect(requester.getByText('Actions are read-only for Requesters.', { exact: true })).toBeVisible();
        await expect(requester.getByRole('button', { name: 'Add Action', exact: true })).toHaveCount(0);
        await expect(requester.getByText(/PRIVATE diagnostic/)).toHaveCount(0);
        expect((await requester.request.post(`${api}/tickets/${ticket.id}/actions-taken`, { headers, data: { workflowRevision: revision, requestKey: randomUUID(), description: 'Forbidden' } })).status()).toBe(403);
        expect((await requester.request.patch(`${api}/tickets/${ticket.id}/actions-taken/${actionId}`, { headers, data: { workflowRevision: revision, result: 'Forbidden' } })).status()).toBe(403);
        expect((await requester.request.get(`${api}/staff/tickets/${ticket.id}/notes`)).status()).toBe(403);
        const detail = await requester.request.get(`${api}/tickets/${ticket.id}`);
        expect(await detail.text()).not.toContain('PRIVATE diagnostic');
        await expect(requester.getByRole('article', { name: `Action ${actionId}`, exact: true }).getByRole('heading')).toContainText('COMPLETED');
        await expect(requester.getByRole('article', { name: `Action ${second.id}`, exact: true }).getByRole('heading')).toContainText('CANCELLED');
        await capture(requester, info, 'actions-taken', 'requester-read-only', 'REQUESTER', ['AC-03', 'AC-07', 'AC-08', 'AC-09', 'AC-24'], 'Completed and cancelled shared lines, Requester read-only and private-note exclusion');
    }
    finally {
        await context.close();
    }
    await info.attach('database-reconciliation', { body: JSON.stringify({ actionIds: [actionId, second.id], events: events.map((e: any) => e.eventType), successfulPlannedEdit: true, inactiveAssigneeAbsent: true, immutableIdentity: true, auditEventsAppendOnly: true, stableOrdering: true, retryNoDuplicate: true, invalidWritesRolledBack: true }), contentType: 'application/json' });
});
