test('E2E-WF-01 — Requester create, persisted retry, comments, advisory and attachment continuity', async ({ page, lab }, info) => {
    expect((await page.request.get(`${api}/tickets`)).status()).toBe(401);
    expect((await page.request.get(`${api}/dashboard/requester`)).status()).toBe(401);
    expect((await page.request.get(`${api}/tickets`, { headers: { 'X-Requester-Id': String(lab.users.requester.id) } })).status()).toBe(401);
    const before = await lab.db.ticket.findMany({ orderBy: { id: 'asc' } });
    await login(page, 'requester');
    await nav(page, /Create Ticket/);
    await expect(page.getByLabel('Ticket Number (Auto-Generated)', { exact: true })).toHaveAccessibleName('Ticket Number (Auto-Generated)');
    await page.locator('#categoryId').selectOption(String(lab.category.id));
    await page.locator('#relatedSystemId').selectOption(String(lab.system.id));
    await page.locator('#requestedPriority').selectOption('HIGH');
    await page.getByLabel(/Ticket Summary/).fill('Integrated Requester ticket creation with real PostgreSQL');
    await page.getByLabel(/Detailed Description/).fill('Verify the entire authenticated frontend API database path, including safe retries.');
    const created = page.waitForResponse(r => r.url() === `${api}/tickets` && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Submit Ticket', exact: true }).click();
    const response = await created;
    expect(response.status()).toBe(201);
    const body = await response.json();
    const ticket = body.ticket ?? body;
    await expect(page.getByRole('heading', { level: 1, name: /Ticket Created Successfully/ })).toBeVisible();
    const persistedCreate = await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } });
    expect(persistedCreate).toMatchObject({ requesterId: lab.users.requester.id, categoryId: lab.category.id, relatedSystemId: lab.system.id, requestedPriority: 'HIGH', itPriority: 'HIGH' });
    expect(persistedCreate.creationPayloadHash).toMatch(/^[a-f0-9]{64}$/);
    const key = response.request().headers()['idempotency-key'];
    expect(key).toBeTruthy();
    const replay = await page.request.post(`${api}/tickets`, { headers: { ...headers, 'Idempotency-Key': key }, data: response.request().postDataJSON() });
    expect(replay.status()).toBe(201);
    expect(await replay.json()).toEqual(body);
    const conflict = await page.request.post(`${api}/tickets`, { headers: { ...headers, 'Idempotency-Key': key }, data: { ...response.request().postDataJSON(), summary: 'Different payload' } });
    expect(conflict.status()).toBe(409);
    expect(await lab.db.ticket.count({ where: { creationRequestKey: key, requesterId: lab.users.requester.id } })).toBe(1);
    await openTicket(page, ticket.ticketNumber);
    await page.locator('#newComment').fill('Public comment from authenticated Requester.');
    await page.getByRole('button', { name: 'Post Comment', exact: true }).click();
    await expect(page.getByText('Public comment from authenticated Requester.', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: /Problem Appears Resolved/ }).click();
    await page.getByLabel(/Resolution Comment/).fill('The problem appears resolved; staff must verify formal status.');
    await page.getByRole('button', { name: 'Submit Resolution Comment', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    expect((await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } })).currentStatus).toBe('NEW');
    expect(await lab.db.comment.count({ where: { ticketId: ticket.id, authorId: lab.users.requester.id } })).toBe(2);
    const bytes = Buffer.from('%PDF-1.4\nIssue 27 real attachment continuity\n%%EOF');
    await page.locator('#attachment-upload-input').setInputFiles({ name: 'lab4-evidence.pdf', mimeType: 'application/pdf', buffer: bytes });
    const uploaded = page.waitForResponse(r => r.url().endsWith(`/tickets/${ticket.id}/attachments`) && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Upload File', exact: true }).click();
    expect((await uploaded).status()).toBe(201);
    await expect(page.getByText('lab4-evidence.pdf', { exact: true })).toBeVisible();
    const attachment = await lab.db.attachment.findFirstOrThrow({ where: { ticketId: ticket.id } });
    expect(readFileSync(attachment.filePath)).toEqual(bytes);
    const download = await page.request.get(`${api}/attachments/${attachment.id}/download`);
    expect(download.status()).toBe(200);
    expect(await download.body()).toEqual(bytes);
    await page.getByRole('button', { name: 'Remove', exact: true }).click();
    await page.getByLabel(/Removal Reason/).fill('Replaced by the verified corrected document.');
    await page.getByRole('button', { name: 'Confirm Removal', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.getByRole('heading', { name: /Attachments 0 \/ 5 active/ })).toBeFocused();
    const removed = await lab.db.attachment.findUniqueOrThrow({ where: { id: attachment.id } });
    expect(removed.isRemoved).toBe(true);
    expect(removed.removedByRequesterId).toBe(lab.users.requester.id);
    expect(readFileSync(removed.filePath)).toEqual(bytes);
    expect((await page.request.get(`${api}/attachments/${attachment.id}/download`)).status()).toBe(410);
    const unowned = await page.request.get(`${api}/tickets/${lab.foreign.id}`);
    const missing = await page.request.get(`${api}/tickets/2147483647`);
    expect(unowned.status()).toBe(404);
    expect(missing.status()).toBe(404);
    expect(await unowned.json()).toEqual(await missing.json());
    expect((await page.request.get(`${api}/tickets/${lab.foreign.id}/actions-taken`)).status()).toBe(404);
    expect((await page.request.patch(`${api}/staff/tickets/${ticket.id}/status`, { headers, data: { workflowRevision: 0, status: 'OPEN' } })).status()).toBe(403);
    expect((await page.request.get(`${api}/admin/users`)).status()).toBe(403);
    await nav(page, 'Dashboard');
    await expect(page.getByRole('button', { name: 'View New (2)', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'View New (2)', exact: true }).click();
    await expect(page.locator('#ticket-status-filter')).toHaveValue('NEW');
    await expect(page.getByRole('button', { name: ticket.ticketNumber, exact: true })).toBeVisible();
    await page.reload();
    await openTicket(page, ticket.ticketNumber);
    await expect(page.getByText('Public comment from authenticated Requester.', { exact: true })).toBeVisible();
    expect(await lab.db.ticket.findMany({ where: { id: { not: ticket.id } }, orderBy: { id: 'asc' } })).toEqual(before);
    await info.attach('database-reconciliation', { body: JSON.stringify({ ticketId: ticket.id, requesterId: lab.users.requester.id, ticketReplayCount: 1, comments: 2, advisoryStatus: 'NEW', attachmentId: attachment.id, softRemovalPreservesBytes: true, reloadPersistence: true, crossOwner404: true }), contentType: 'application/json' });
});
test('E2E-WF-02 — real resolution gate, stale draft recovery, corrections, closure and zero-Action policy', async ({ page, lab, browser }, info) => {
    const ticket = lab.tickets[2];
    await login(page, 'staff');
    await openTicket(page, ticket.ticketNumber, true);
    await page.getByRole('button', { name: 'Claim Ticket', exact: true }).click();
    await expect(page.getByText('Ticket claimed successfully.', { exact: true })).toBeVisible();
    await page.getByLabel('Assigned Owner', { exact: true }).selectOption(String(lab.users.second.id));
    await expect(page.getByText('Ticket assignment updated successfully.', { exact: true })).toBeVisible();
    await page.getByLabel('IT Priority', { exact: true }).selectOption('URGENT');
    await expect(page.getByText('IT Priority updated successfully.', { exact: true })).toBeVisible();
    expect((await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } })).assignedStaffId).toBe(lab.users.second.id);
    await page.getByRole('button', { name: 'Add Action', exact: true }).click();
    const form = page.getByRole('form', { name: 'Create Action', exact: true });
    await form.getByLabel('Description', { exact: true }).fill('Investigate and verify the resolution gate.');
    await form.getByLabel('Follow-Up Required', { exact: true }).check();
    await form.getByLabel('Follow-Up Note', { exact: true }).fill('Independent confirmation is required.');
    await form.getByRole('button', { name: 'Create Action', exact: true }).click();
    await expect(form).toHaveCount(0);
    const action = await lab.db.actionTaken.findFirstOrThrow({ where: { ticketId: ticket.id } });
    let persisted = await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } });
    await expect(page.getByRole('link', { name: 'Review Actions Taken', exact: true })).toHaveCount(0);
    await page.getByLabel('Update Status', { exact: true }).selectOption('RESOLVED');
    await expect(page.getByRole('button', { name: 'Save Transition to RESOLVED', exact: true })).toBeDisabled();
    const blocked = await page.request.patch(`${api}/staff/tickets/${ticket.id}/status`, { headers, data: { workflowRevision: persisted.workflowRevision, status: 'RESOLVED' } });
    expect(blocked.status()).toBe(409);
    expect((await blocked.json()).code).toBe('RESOLUTION_BLOCKED');
    expect((await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } })).workflowRevision).toBe(persisted.workflowRevision);
    await page.getByRole('button', { name: 'Dismiss success message', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'Complete or cancel planned Actions, then clear any required follow-up' })).toBeVisible();
    if (info.project.name === 'desktop')
        await capture(page, info, 'actions-taken', 'blocked-resolution', 'IT_STAFF', ['AC-12', 'AC-13', 'AC-24'], 'Selecting resolution explains outstanding work; frontend save and direct API resolution remain blocked without mutation');
    const article = page.getByRole('article', { name: `Action ${action.id}`, exact: true });
    await article.getByRole('button', { name: 'Edit Action', exact: true }).click();
    const edit = page.getByRole('form', { name: 'Edit Action', exact: true });
    await edit.getByLabel('Result', { exact: true }).fill('Retained draft while another Staff user updates the Action.');
    const other = await browser.newContext();
    try {
        const request = other.request;
        expect((await request.post(`${api}/auth/login`, { headers, data: { email: 'second@lab4.test', password: 'Lab4Test123!' } })).status()).toBe(200);
        const update = await request.patch(`${api}/tickets/${ticket.id}/actions-taken/${action.id}`, { headers, data: { workflowRevision: persisted.workflowRevision, attachmentNotes: 'Newer work from Taylor' } });
        expect(update.status()).toBe(200);
    }
    finally {
        await other.close();
    }
    const stale = page.waitForResponse(r => r.url().endsWith(`/actions-taken/${action.id}`) && r.request().method() === 'PATCH');
    await edit.getByRole('button', { name: 'Save changes', exact: true }).click();
    expect((await stale).status()).toBe(409);
    await expect(edit.getByLabel('Result', { exact: true })).toHaveValue('Retained draft while another Staff user updates the Action.');
    await expect(page.getByRole('button', { name: 'Refresh and review', exact: true })).toBeVisible();
    if (info.project.name === 'desktop')
        await capture(page, info, 'actions-taken', 'stale-conflict', 'IT_STAFF', ['AC-10', 'AC-20', 'AC-24'], 'A real second Staff session wins; 409 retains the first browser draft', 'Newer work or a conflicting request exists.');
    await page.getByRole('button', { name: 'Refresh and review', exact: true }).click();
    await expect(page.getByRole('button', { name: 'I have reviewed the latest Actions', exact: true })).toBeEnabled();
    await page.getByRole('button', { name: 'I have reviewed the latest Actions', exact: true }).click();
    await edit.getByRole('button', { name: 'Complete Action', exact: true }).click();
    await expect(article.getByRole('heading')).toContainText('COMPLETED');
    persisted = await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } });
    expect((await page.request.patch(`${api}/staff/tickets/${ticket.id}/status`, { headers, data: { workflowRevision: persisted.workflowRevision, status: 'RESOLVED' } })).status()).toBe(409);
    await article.getByRole('button', { name: 'Correct completed Action', exact: true }).click();
    await edit.getByLabel('Follow-Up Required', { exact: true }).uncheck();
    await edit.getByRole('button', { name: 'Save changes', exact: true }).click();
    await expect(edit).toHaveCount(0);
    const corrected = await lab.db.actionTaken.findUniqueOrThrow({ where: { id: action.id } });
    expect(corrected.status).toBe('COMPLETED');
    expect(corrected.createdAt).toEqual(action.createdAt);
    expect(corrected.followUpRequired).toBe(false);
    expect(corrected.attachmentNotes).toBe('Newer work from Taylor');
    await expect(page.locator('#update-status-select option[value="RESOLVED"]')).toBeEnabled();
    await expect(page.getByRole('link', { name: 'Review Actions Taken', exact: true })).toHaveCount(0);
    await page.getByLabel('Update Status', { exact: true }).selectOption('RESOLVED');
    await page.getByLabel(/Resolution Summary/).fill('Verified fix and all follow-up work complete.');
    await page.getByRole('button', { name: 'Save Transition to RESOLVED', exact: true }).click();
    await expect(page.getByText(/Reopen this Ticket before adding or correcting Actions/)).toBeVisible();
    persisted = await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } });
    expect(persisted.currentStatus).toBe('RESOLVED');
    expect((await page.request.post(`${api}/tickets/${ticket.id}/actions-taken`, { headers, data: { workflowRevision: persisted.workflowRevision, requestKey: randomUUID(), description: 'Forbidden terminal write' } })).status()).toBe(409);
    await page.getByLabel('Update Status', { exact: true }).selectOption('CLOSED');
    await page.getByRole('button', { name: 'Save Transition to CLOSED', exact: true }).click();
    await expect(page.locator('#update-status-select')).toHaveValue('CLOSED');
    await page.getByLabel('Update Status', { exact: true }).selectOption('REOPENED');
    await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click();
    await page.getByRole('button', { name: 'Save Transition to REOPENED', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Add Action', exact: true })).toBeEnabled();
    const legacy = lab.tickets[1];
    expect(await lab.db.actionTaken.count({ where: { ticketId: legacy.id } })).toBe(0);
    await openTicket(page, legacy.ticketNumber, true);
    await expect(page.getByText('No Actions Taken yet.', { exact: true })).toBeVisible();
    await page.getByLabel('Update Status', { exact: true }).selectOption('RESOLVED');
    await page.getByRole('button', { name: 'Save Transition to RESOLVED', exact: true }).click();
    await expect(page.locator('#update-status-select')).toHaveValue('RESOLVED');
    expect(await lab.db.actionTaken.count({ where: { ticketId: legacy.id } })).toBe(0);
    await openTicket(page, lab.tickets[0].ticketNumber, true);
    await page.getByLabel('Update Status', { exact: true }).selectOption('CANCELLED');
    await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click();
    await page.getByRole('button', { name: 'Save Transition to CANCELLED', exact: true }).click();
    await expect(page.getByText('This Ticket is cancelled. Actions are read-only.', { exact: true })).toBeVisible();
    expect((await lab.db.ticket.findUniqueOrThrow({ where: { id: lab.tickets[0].id } })).currentStatus).toBe('CANCELLED');
    await info.attach('database-reconciliation', { body: JSON.stringify({ ticketId: ticket.id, plannedGate409: true, followUpGate409: true, stale409: true, finalStatus: (await lab.db.ticket.findUniqueOrThrow({ where: { id: ticket.id } })).currentStatus, correctedStatus: corrected.status, legacyNoFabricatedActions: true }), contentType: 'application/json' });
});
